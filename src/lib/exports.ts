import type { Built, Col, Row } from "./reports";
import { fmtDate } from "./lifecycle";
import logoUrl from "../assets/slt-logo.png";

export interface ExportMeta {
  title: string;
  filters: string;
  generatedBy: string;
  generatedAt: string;
  definitions: string[];
}

function download(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 2000);
}

const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
export const fileBase = (m: ExportMeta) => `comtrack-${slug(m.title)}-${m.generatedAt.slice(0, 10)}`;

const cellText = (c: Col, v: Row[string]) => (v === null || v === undefined || v === "" ? "" : c.type === "date" ? fmtDate(String(v), true) : String(v));

// ── CSV ─────────────────────────────────────────────────────────
export function csvEscape(v: string) {
  let s = v;
  if (/^[=+\-@\t\r]/.test(s)) s = "'" + s; // spreadsheet formula-injection guard
  return /[",\r\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}
export function toCsv(b: Built) {
  const head = b.columns.map((c) => csvEscape(c.label)).join(",");
  const lines = b.rows.map((r) => b.columns.map((c) => {
    const v = r[c.key];
    if (v === null || v === undefined) return "";
    if (c.type === "number") return String(v);
    if (c.type === "date") return csvEscape(new Date(String(v)).toISOString());
    return csvEscape(String(v));
  }).join(","));
  return "\uFEFF" + [head, ...lines].join("\r\n");
}
export function exportCsv(b: Built, m: ExportMeta) {
  download(new Blob([toCsv(b)], { type: "text/csv;charset=utf-8" }), fileBase(m) + ".csv");
}

// ── Excel (.xlsx genuine workbook) ──────────────────────────────
export async function exportXlsx(b: Built, m: ExportMeta) {
  const ExcelJS = (await import("exceljs")).default;
  const wb = new ExcelJS.Workbook();
  wb.creator = "ComTrack (prototype)";
  wb.created = new Date();
  const blue = "FF0A4595";

  const sum = wb.addWorksheet("Summary");
  sum.columns = [{ width: 38 }, { width: 70 }];
  sum.addRow(["SLT ComTrack — " + m.title]).font = { bold: true, size: 14, color: { argb: blue } };
  sum.addRow([]);
  const meta: [string, string][] = [["Report", m.title], ["Filters", m.filters], ["Generated by", m.generatedBy], ["Generated at (Asia/Colombo)", fmtDate(m.generatedAt, true)], ["Rows in detail sheet", String(b.rows.length)]];
  meta.forEach(([k, v]) => { const r = sum.addRow([k, v]); r.getCell(1).font = { bold: true }; });
  sum.addRow([]);
  sum.addRow(["Summary metric", "Value"]).font = { bold: true, color: { argb: "FFFFFFFF" } };
  sum.lastRow!.eachCell((c) => (c.fill = { type: "pattern", pattern: "solid", fgColor: { argb: blue } }));
  b.summary.forEach((s) => sum.addRow([s.label, s.value]));
  if (b.groups) {
    sum.addRow([]);
    sum.addRow(["Group", "Count"]).font = { bold: true };
    b.groups.forEach((g) => sum.addRow([g.key, g.count]));
  }

  const det = wb.addWorksheet("Detail", { views: [{ state: "frozen", ySplit: 1 }] });
  det.columns = b.columns.map((c) => ({
    header: c.label, key: c.key,
    width: Math.min(60, Math.max(c.label.length + 2, c.type === "date" ? 18 : 12, ...b.rows.slice(0, 200).map((r) => String(r[c.key] ?? "").length + 2))),
    style: c.type === "date" ? { numFmt: "dd mmm yyyy hh:mm" } : c.type === "number" ? { numFmt: "0.0" } : {},
  }));
  b.rows.forEach((r) => det.addRow(Object.fromEntries(b.columns.map((c) => {
    const v = r[c.key];
    if (v === null || v === undefined || v === "") return [c.key, null];
    // shift to Colombo wall time so the spreadsheet shows local timestamps
    if (c.type === "date") return [c.key, new Date(new Date(String(v)).getTime() + 330 * 60000)];
    if (c.type === "number") return [c.key, Number(v)];
    return [c.key, String(v)];
  }))));
  const header = det.getRow(1);
  header.font = { bold: true, color: { argb: "FFFFFFFF" } };
  header.eachCell((c) => (c.fill = { type: "pattern", pattern: "solid", fgColor: { argb: blue } }));
  if (b.columns.length) det.autoFilter = { from: { row: 1, column: 1 }, to: { row: Math.max(1, b.rows.length + 1), column: b.columns.length } };

  const defs = wb.addWorksheet("Definitions");
  defs.columns = [{ width: 120 }];
  defs.addRow(["Calculation definitions & populations"]).font = { bold: true };
  m.definitions.forEach((d) => defs.addRow([d]));
  defs.addRow(["Exports include every filtered record within your authorised scope, not only the visible page. Attachment binaries and unauthorised fields are excluded."]);

  const buf = await wb.xlsx.writeBuffer();
  download(new Blob([buf], { type: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet" }), fileBase(m) + ".xlsx");
}

// ── PDF ─────────────────────────────────────────────────────────
// Standard PDF fonts cannot render Sinhala/Tamil glyphs; such runs are marked rather than garbled.
const latin = (s: string) => s.replace(/[^\u0000-\u024F\u2013\u2014\u2018-\u201D\u2022\u2026\u00B7]+/g, "[Sinhala/Tamil text — see Excel/CSV]");

async function logoData(): Promise<string | null> {
  try {
    const blob = await (await fetch(logoUrl)).blob();
    return await new Promise((res) => { const r = new FileReader(); r.onload = () => res(String(r.result)); r.readAsDataURL(blob); });
  } catch {
    return null;
  }
}

export async function exportPdf(b: Built, m: ExportMeta) {
  const { jsPDF } = await import("jspdf");
  const autoTable = (await import("jspdf-autotable")).default;
  const wide = b.columns.length > 7;
  const doc = new jsPDF({ orientation: wide ? "landscape" : "portrait", unit: "pt", format: "a4" });
  const W = doc.internal.pageSize.getWidth();
  const M = 36;
  const logo = await logoData();

  doc.setFillColor(10, 69, 149);
  doc.rect(0, 0, W, 6, "F");
  if (logo) doc.addImage(logo, "PNG", M, 18, 70, 26);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(9);
  doc.setTextColor(10, 69, 149);
  doc.text("ComTrack · Complaint Management & Tracking", W - M, 30, { align: "right" });
  doc.setFontSize(18);
  doc.setTextColor(16, 35, 60);
  doc.text(latin(m.title), M, 72);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(69, 86, 109);
  const fl = doc.splitTextToSize(latin(m.filters), W - 2 * M);
  doc.text(fl, M, 88);
  let y = 88 + fl.length * 11 + 4;
  doc.text(`Generated by ${latin(m.generatedBy)} · ${fmtDate(m.generatedAt, true)} (Asia/Colombo) · ${b.rows.length} records`, M, y);
  y += 16;

  // Summary cards
  const cw = (W - 2 * M - 10 * 2) / 3;
  b.summary.forEach((s, i) => {
    const x = M + (i % 3) * (cw + 10);
    const yy = y + Math.floor(i / 3) * 46;
    doc.setDrawColor(226, 232, 241);
    doc.setFillColor(250, 251, 253);
    doc.roundedRect(x, yy, cw, 38, 4, 4, "FD");
    doc.setFontSize(8);
    doc.setTextColor(122, 136, 156);
    doc.text(latin(s.label), x + 8, yy + 13);
    doc.setFontSize(13);
    doc.setFont("helvetica", "bold");
    doc.setTextColor(16, 35, 60);
    doc.text(s.value, x + 8, yy + 30);
    doc.setFont("helvetica", "normal");
  });
  y += Math.ceil(b.summary.length / 3) * 46 + 8;

  // Chart (simple horizontal bars drawn as vectors)
  if (b.chart && b.chart.data.length && b.rows.length) {
    doc.setFontSize(10);
    doc.setFont("helvetica", "bold");
    doc.setTextColor(16, 35, 60);
    doc.text(latin(b.chart.label), M, y + 4);
    doc.setFont("helvetica", "normal");
    y += 12;
    const data = b.chart.data.slice(0, 8);
    const max = Math.max(...data.map((d) => d.value), 1);
    const barW = W - 2 * M - 150;
    data.forEach((d, i) => {
      const yy = y + i * 15;
      doc.setFontSize(8);
      doc.setTextColor(69, 86, 109);
      doc.text(latin(d.name).slice(0, 28), M, yy + 8);
      doc.setFillColor(i === 0 ? 10 : 88, i === 0 ? 69 : 167, i === 0 ? 149 : 51);
      doc.rect(M + 120, yy, Math.max(2, (d.value / max) * barW), 10, "F");
      doc.text(String(d.value), M + 124 + (d.value / max) * barW, yy + 8);
    });
    y += data.length * 15 + 12;
  }

  if (!b.rows.length) {
    doc.setFontSize(11);
    doc.setTextColor(69, 86, 109);
    doc.text("No records match the selected period and filters.", M, y + 14);
  } else {
    autoTable(doc, {
      startY: y,
      head: [b.columns.map((c) => c.label)],
      body: b.rows.map((r) => b.columns.map((c) => latin(cellText(c, r[c.key])))),
      styles: { font: "helvetica", fontSize: wide ? 7 : 8, cellPadding: 3, overflow: "linebreak", textColor: [16, 35, 60] },
      headStyles: { fillColor: [10, 69, 149], textColor: 255, fontStyle: "bold" },
      alternateRowStyles: { fillColor: [244, 246, 250] },
      showHead: "everyPage",
      margin: { left: M, right: M, bottom: 40 },
    });
  }

  // Definitions page
  doc.addPage();
  doc.setFontSize(12);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(16, 35, 60);
  doc.text("Definitions & populations", M, 50);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  let dy = 70;
  [...m.definitions, "Includes every filtered record within the generating user's authorised scope. Attachment binaries and unauthorised fields are excluded."].forEach((d) => {
    const lines = doc.splitTextToSize("• " + d, W - 2 * M);
    doc.text(lines, M, dy);
    dy += lines.length * 12 + 4;
  });

  const pages = doc.getNumberOfPages();
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i);
    const H = doc.internal.pageSize.getHeight();
    doc.setFontSize(8);
    doc.setTextColor(122, 136, 156);
    doc.text("SLT ComTrack · Confidential — internal use", M, H - 18);
    doc.text(`Page ${i} of ${pages}`, W - M, H - 18, { align: "right" });
  }
  doc.save(fileBase(m) + ".pdf");
}
